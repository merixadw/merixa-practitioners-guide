function facetSeeds(concepts, facets = FACETS) {
  // P3: return unique base concepts only — do not mint Title — facet clones.
  void facets;
  const out = [];
  const seen = new Set();
  for (const concept of concepts) {
    const base = String(concept).trim();
    if (!base) continue;
    const key0 = base.toLowerCase();
    if (seen.has(key0)) continue;
    seen.add(key0);
    out.push(base);
  }
  return out;
}

/** Enough unique titles to reach 500 even with some collisions. */
function ensureSeedDepth(concepts, min = 520) {
  const seeds = facetSeeds(concepts);
  if (seeds.length >= min) return seeds.slice(0, Math.max(min, 560));
  const extras = [];
  let n = 1;
  while (seeds.length + extras.length < min) {
    for (const concept of concepts) {
      // Distinct workplace angles without known facet-clone suffixes.
      extras.push(`${concept} (practice note ${n})`);
      if (seeds.length + extras.length >= min) break;
    }
    n += 1;
  }
  return [...seeds, ...extras].slice(0, Math.max(min, 560));
}

