/** All shelves: classic encyclopedia packs + domain-floor + tax jurisdictions. */
export const ALL_ENCYCLOPEDIA_SHELVES = [
  ...ENCYCLOPEDIA_SHELVES,
  ...DOMAIN_FLOOR_SHELVES,
  ...TAX_JURISDICTION_SHELVES,
];

export function shelfExistingCount(cards, shelf) {
  if (shelf.countByTaxFloor) {
    return taxEncyclopediaCount(cards);
  }
  if (shelf.countByDomain) {
    return domainFloorCount(cards, shelf.domain);
  }
  const match = shelf.idMatch;
  return (cards || []).filter((card) => {
    const id = String(card.id || "");
    if (match instanceof RegExp) return match.test(id);
    return id.startsWith(shelf.idPrefix);
  }).length;
}

/** Target cards for a shelf (floors — expansion continues until gap is closed). */
export function shelfTarget(shelf) {
  if (Number.isFinite(shelf?.target) && shelf.target > 0) {
    return Math.floor(shelf.target);
  }
  if (shelf.countByTaxFloor) return Math.max(TAX_FLOOR_TARGET, ENCYCLOPEDIA_SHELF_TARGET);
  return ENCYCLOPEDIA_SHELF_TARGET;
}
