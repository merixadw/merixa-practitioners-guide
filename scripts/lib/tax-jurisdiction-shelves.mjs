function uniqueList(items) {
  const seen = new Set();
  const out = [];
  for (const item of items) {
    const key = String(item || "")
      .toLowerCase()
      .replace(/\s+/g, " ")
      .trim();
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(String(item).trim());
  }
  return out;
}

export function taxEncyclopediaCount(cards) {
  return (cards || []).filter((card) => {
    const id = String(card?.id || "");
    if (id.startsWith("tax-")) return true;
    const tags = Array.isArray(card?.tags) ? card.tags : [];
    return tags.includes("tax-encyclopedia");
  }).length;
}

export function taxJurisdictionCount(cards, jurisdiction) {
  const tag = `tax-${jurisdiction}`;
  const prefix = `tax-${jurisdiction}-`;
  return (cards || []).filter((card) => {
    const id = String(card?.id || "");
    if (id.startsWith(prefix)) return true;
    const tags = Array.isArray(card?.tags) ? card.tags : [];
    return tags.includes(tag) || tags.includes(`tax-jurisdiction-${jurisdiction}`);
  }).length;
}

